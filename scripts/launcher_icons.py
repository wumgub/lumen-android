#!/usr/bin/env python3
"""Generate Lumen's launcher icon variants.

Each theme gets an icon in its own colours, plus a palette of extra colours
the Custom theme can pick from. For every variant this writes the adaptive
icon's background and foreground drawables and its mipmap, then the Kotlin
list the app reads (theme/AppIcons.kt) and the manifest's activity-aliases
(between the LAUNCHER ICONS markers). Run it from the repo root after
changing a colour here:

    python3 scripts/launcher_icons.py
"""
import colorsys
import re
from pathlib import Path

RES = Path("app/src/main/res")
KOTLIN = Path("app/src/main/java/com/lumen/android/theme/AppIcons.kt")
MANIFEST = Path("app/src/main/AndroidManifest.xml")


def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def hexs(c, alpha=0xFF):
    return "#%02x%02x%02x%02x" % ((alpha,) + tuple(max(0, min(255, round(v))) for v in c))


def mix(a, b, t):
    return tuple(x + (y - x) * t for x, y in zip(a, b))


def hsl(h, s, l):
    r, g, b = colorsys.hls_to_rgb((h % 360) / 360, l, s)
    return (r * 255, g * 255, b * 255)


BLACK, WHITE = (0, 0, 0), (255, 255, 255)


class Icon:
    def __init__(self, id, label, tile, bars, glow, light=False, theme=False):
        self.id, self.label = id, label
        self.tile, self.bars, self.glow = tile, bars, glow  # 3 stops, 3 stops, 2 colours
        self.light, self.theme = light, theme

    @property
    def res(self):
        return self.id.replace("-", "_")


def from_theme(id, label, bg, accent, accent2, light=False):
    bg, a, a2 = rgb(bg), rgb(accent), rgb(accent2)
    if light:
        tile = (mix(bg, a, 0.10), bg, mix(bg, BLACK, 0.06))
    else:
        tile = (mix(bg, a, 0.16), bg, mix(bg, BLACK, 0.45))
    return Icon(id, label, tile, (a, mix(a, a2, 0.5), a2), (a, a2), light=light, theme=True)


def from_hue(id, label, hue):
    bars = (hsl(hue, 0.9, 0.62), hsl(hue + 28, 0.85, 0.62), hsl(hue + 56, 0.85, 0.68))
    tile = (hsl(hue, 0.55, 0.16), hsl(hue, 0.35, 0.07), (7, 7, 14))
    return Icon(id, label, tile, bars, (bars[0], bars[2]))


ICONS = [
    # Neon keeps the original icon's colours exactly.
    Icon("neon", "Neon", ((0x1b, 0x11, 0x40), (0x0d, 0x0b, 0x1f), (0x07, 0x07, 0x0e)),
         ((0x2a, 0xd8, 0xff), (0x9b, 0x6b, 0xff), (0xff, 0x72, 0xe2)),
         ((0x36, 0xd6, 0xff), (0x8a, 0x5c, 0xff)), theme=True),
    from_theme("minimal", "Flashbang", "#f7f7f9", "#5b6ccf", "#e0607e", light=True),
    from_theme("minimal-dark", "Minimal Dark", "#121316", "#7c8cff", "#f0879f"),
    from_theme("retro", "Retro", "#10140f", "#a3e635", "#f59e0b"),
    from_theme("glass", "Glass", "#0c1018", "#7dd3fc", "#f0abfc"),
    Icon("blackout", "Blackout", ((0x10, 0x10, 0x10), BLACK, BLACK),
         ((0xa5, 0xf3, 0xfc), (0x22, 0xd3, 0xee), (0x08, 0x91, 0xb2)),
         ((0x22, 0xd3, 0xee), (0x22, 0xd3, 0xee)), theme=True),
] + [from_hue(id, label, hue) for id, label, hue in [
    ("red", "Red", 355), ("orange", "Orange", 22), ("amber", "Amber", 40), ("yellow", "Yellow", 52),
    ("lime", "Lime", 82), ("green", "Green", 140), ("teal", "Teal", 170), ("cyan", "Cyan", 190),
    ("blue", "Blue", 215), ("indigo", "Indigo", 238), ("purple", "Purple", 268), ("pink", "Pink", 320),
]]

# The five bars, as (x, top of the straight part, its length), in the desktop
# icon's 1024 space.
BARS = [(208, 466, 92), (338, 346, 332), (468, 406, 212), (598, 321, 382), (728, 441, 142)]

HEAD = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/launcher_icons.py: change the colours there. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="1344"
    android:viewportHeight="1344">
"""


def gradient(kind, attrs, stops, indent=12):
    sp = " " * indent
    items = "".join(f'\n{sp}        <item android:offset="{o}" android:color="{c}" />' for o, c in stops)
    return (f'{sp}<aapt:attr name="android:fillColor">\n'
            f'{sp}    <gradient android:type="{kind}" {attrs}>{items}\n'
            f'{sp}    </gradient>\n{sp}</aapt:attr>\n')


def pill(x, top, length, r, inset):
    return f"M{x - inset},{top}.0 a{r}.0,{r}.0 0 0 1 {2 * r},0 v{length}.0 a{r}.0,{r}.0 0 0 1 -{2 * r},0 z"


def background(icon):
    t = icon.tile
    sheen = 0x26 if icon.light else 0x1A
    return (HEAD
            + '    <path android:pathData="M0,0 h1344 v1344 h-1344 z">\n'
            + gradient("linear", 'android:startX="160" android:startY="160" android:endX="1184" android:endY="1184"',
                       [(0, hexs(t[0])), (0.55, hexs(t[1])), (1, hexs(t[2]))], indent=8)
            + '    </path>\n'
            + '    <path android:pathData="M0,0 h1344 v1344 h-1344 z">\n'
            + gradient("linear", 'android:startX="0" android:startY="160" android:endX="0" android:endY="518"',
                       [(0, hexs(WHITE, sheen)), (1, hexs(WHITE, 0))], indent=8)
            + '    </path>\n</vector>\n')


def foreground(icon):
    g1, g2 = icon.glow
    strength = 0.6 if icon.light else 1.0
    out = [HEAD, '    <group android:translateX="160" android:translateY="160">\n',
           '        <path android:pathData="M172,540 a340,340 0 1 1 680,0 a340,340 0 1 1 -680,0 z">\n',
           gradient("radial", 'android:centerX="512" android:centerY="540" android:gradientRadius="340"',
                    [(0, hexs(g1, round(0x80 * strength))), (0.6, hexs(g2, round(0x2E * strength))), (1, hexs(g2, 0))]),
           '        </path>\n']
    # A few translucent pills around each bar stand in for a blur.
    for r, alpha in ((80, 0x10), (68, 0x14), (56, 0x1F)):
        for x, top, length in BARS:
            a = round(alpha * strength)
            out.append(f'        <path android:fillColor="{hexs(g1, a)}" android:pathData="{pill(x, top, length, r, r - 44)}" />\n')
    b = icon.bars
    for x, top, length in BARS:
        out.append(f'        <path android:pathData="{pill(x, top, length, 44, 0)}">\n')
        out.append(gradient("linear", f'android:startX="{x}" android:startY="{top - 44}" android:endX="{x}" android:endY="{top + length + 44}"',
                            [(0, hexs(b[0])), (0.5, hexs(b[1])), (1, hexs(b[2]))]))
        out.append('        </path>\n')
    out.append('    </group>\n</vector>\n')
    return "".join(out)


def mipmap(icon):
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/launcher_icons.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_bg_{icon.res}" />
    <foreground android:drawable="@drawable/ic_launcher_fg_{icon.res}" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""


def alias(icon):
    # Neon is the alias named after the old launcher activity, so the home
    # screen shortcut people already have keeps working after updating.
    name = ".MainActivity" if icon.id == "neon" else ".icon." + "".join(p.title() for p in icon.id.split("-"))
    return name


def main():
    for old in list(RES.glob("drawable/ic_launcher_bg_*.xml")) + list(RES.glob("drawable/ic_launcher_fg_*.xml")) \
            + list(RES.glob("mipmap-anydpi-v26/ic_launcher_*.xml")):
        old.unlink()
    (RES / "mipmap-anydpi-v26").mkdir(exist_ok=True)
    for icon in ICONS:
        (RES / f"drawable/ic_launcher_bg_{icon.res}.xml").write_text(background(icon))
        (RES / f"drawable/ic_launcher_fg_{icon.res}.xml").write_text(foreground(icon))
        (RES / f"mipmap-anydpi-v26/ic_launcher_{icon.res}.xml").write_text(mipmap(icon))

    entries = "\n".join(
        f'    AppIcon("{i.id}", "{i.label}", R.mipmap.ic_launcher_{i.res}, "{alias(i)}", 0x{hexs(i.bars[0])[3:].upper()}, '
        f'{"true" if i.theme else "false"}),'
        for i in ICONS)
    KOTLIN.write_text(f"""// Generated by scripts/launcher_icons.py: change the icons there.
package com.lumen.android.theme

import com.lumen.android.R

/**
 * A launcher icon. [alias] is its activity-alias in the manifest, [color] the
 * top of its bars (for matching a custom accent), and [theme] says it's a
 * theme's own icon rather than one of the extra colours.
 */
data class AppIcon(val id: String, val label: String, val mipmap: Int, val alias: String, val color: Int, val theme: Boolean)

val APP_ICONS = listOf(
{entries}
)
""")

    aliases = "".join(f"""
        <activity-alias
            android:name="{alias(i)}"
            android:targetActivity=".LumenActivity"
            android:enabled="{"true" if i.id == "neon" else "false"}"
            android:exported="true"
            android:icon="@mipmap/ic_launcher_{i.res}"
            android:roundIcon="@mipmap/ic_launcher_{i.res}">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity-alias>""" for i in ICONS)
    m = MANIFEST.read_text()
    m = re.sub(r"(<!-- LAUNCHER ICONS -->).*?(\n\s*<!-- /LAUNCHER ICONS -->)",
               lambda x: x.group(1) + aliases + x.group(2), m, flags=re.S)
    MANIFEST.write_text(m)
    print(f"{len(ICONS)} icons")


if __name__ == "__main__":
    main()
